#!/usr/bin/env python3
"""Generate KuroDeck's palette-dependent Android resources from one table.

Writes into kurodeck/res:
  values/kd_themes.xml          one Launcher3 activity theme per HUD palette
  values/kd_colors.xml          Hearth surface/accent overrides for Material tokens (day)
  values-night/kd_colors.xml    same tokens for night (KuroDeck is always dark)

The palette table mirrors Hearth's style.css and kurodeck/src/com/kurodeck/theme/HudTheme.kt.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "kurodeck", "res")

