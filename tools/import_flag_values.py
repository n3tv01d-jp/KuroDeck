#!/usr/bin/env python3
"""Import shipping aconfig flag values from an AOSP/GrapheneOS `build/release` checkout.

Platform builds resolve each flag through a chain of release configs (ap2a → … → cp2a); the
newest config that mentions a flag wins. Launcher3's "flag off" code paths are not always kept
working once a flag ships, so KuroDeck uses the values Android 17 actually ships with.

Usage:
  tools/import_flag_values.py <build_release_dir> [release ...]
  tools/gen_flags.py
Default chain: ap2a ap3a ap4a bp1a bp2a bp3a bp4a cp1a cp2a
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "flags", "flag_values.properties")
PACKAGES = [
    "com.android.launcher3", "com.android.systemui.shared", "com.android.wm.shell",
    "android.os", "android.multiuser", "android.appwidget.flags", "android.security",
    "com.android.window.flags", "com.android.providers.media.flags",
]
DEFAULT_CHAIN = "ap2a ap3a ap4a bp1a bp2a bp3a bp4a cp1a cp2a".split()
# Flags KuroDeck must keep off regardless of release config (need system privileges / services).
FORCE_OFF = {
    "com.android.launcher3.condo_planner",
}

BLOCK = re.compile(r"flag_value\s*\{(.*?)\}", re.S)
FIELD = re.compile(r'(\w+)\s*:\s*"?([\w.]+)"?')


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    base = sys.argv[1]
    chain = sys.argv[2:] or DEFAULT_CHAIN
    values = {}
    for rel in chain:
        for pkg in PACKAGES:
            for f in sorted(glob.glob(os.path.join(base, "aconfig", rel, pkg, "*.textproto"))):
                for blk in BLOCK.findall(open(f, encoding="utf-8").read()):
                    d = dict(FIELD.findall(blk))
                    if "name" in d and "state" in d:
                        values[f'{d.get("package", pkg)}.{d["name"]}'] = d["state"] == "ENABLED"
    for k in FORCE_OFF:
        values[k] = False
    lines = [
        "# GENERATED by tools/import_flag_values.py from build/release (" + " → ".join(chain) + ").",
        "# <package>.<flag>=true|false ; anything not listed is false. Re-run tools/gen_flags.py after editing.",
    ]
    lines += [f"{k}={'true' if v else 'false'}" for k, v in sorted(values.items())]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    on = sum(values.values())
    print(f"wrote {len(values)} values ({on} enabled) to {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
